void N3DSMenu::openPostcard()
{
	// The zone picture straight from its file, just the postcard's view of it (the drawer can't scale palette sprites)
	mHasPostcardPicture = false;
	const GameMenuEntry& entry = mActiveMenu->selected();
	const std::vector<n3ds::journal::Postcard>& postcards = n3ds::journal::get().mPostcards;
	if (!entry.hasSelected() || entry.selected().mValue >= postcards.size())
		return;
	const std::string spriteName = postcards[entry.selected().mValue].getSpriteName();
	const FunnyPostcard* funny = findFunnyPostcard(postcards[entry.selected().mValue]);
	if (nullptr != funny)
	{
		mHasPostcardPicture = composeFunnyScene(*funny, mPostcardPicture);
		return;
	}

	Bitmap picture;
	if (!FileHelper::loadBitmap(picture, L"data/sprites/zone_preview/" + std::wstring(spriteName.begin(), spriteName.end()) + L".bmp", false) || picture.getWidth() < POSTCARD_VIEW_WIDTH || picture.getHeight() < 80)
		return;
	const PostcardView* view = findPostcardView(spriteName);
	const int center = (nullptr != view) ? (view->mOffset + 100) : (picture.getWidth() / 2);
	const int x0 = clamp(center - POSTCARD_VIEW_WIDTH / 2, 0, picture.getWidth() - POSTCARD_VIEW_WIDTH);

	Bitmap& bitmap = mPostcardPicture.accessBitmap();
	bitmap.create(POSTCARD_VIEW_WIDTH, 80);
	for (int y = 0; y < 80; ++y)
	{
		for (int x = 0; x < POSTCARD_VIEW_WIDTH; ++x)
			*bitmap.getPixelPointer(x, y) = *picture.getPixelPointer(x0 + x, y) | 0xff000000;
	}
	mPostcardPicture.bitmapUpdated();
	mHasPostcardPicture = true;
}

void N3DSMenu::renderPostcard(float alpha)
{
	Drawer& drawer = EngineMain::instance().getDrawer();
	const GameMenuEntry& entry = mActiveMenu->selected();
	const std::vector<n3ds::journal::Postcard>& postcards = n3ds::journal::get().mPostcards;
	if (!entry.hasSelected() || entry.selected().mValue >= postcards.size())
		return;
	const n3ds::journal::Postcard& postcard = postcards[entry.selected().mValue];
	const std::string spriteName = postcard.getSpriteName();
	const PostcardView* view = findPostcardView(spriteName);
	const FunnyPostcard* funny = findFunnyPostcard(postcard);

	// Darken everything, then the card: cream, with a slight shadow, and the picture doubled in size
	drawer.drawRect(Recti(0, 0, (int)mRect.width, (int)mRect.height), Color(0.0f, 0.0f, 0.0f, 0.7f * alpha));
	const Recti card(24, 4, 352, 202);
	drawer.drawRect(Recti(card.x + 4, card.y + 4, card.width, card.height), Color(0.0f, 0.0f, 0.0f, 0.4f * alpha));
	drawer.drawRect(card, Color(0.98f, 0.95f, 0.86f, alpha));
	const Recti pictureRect(card.x + 8, card.y + 6, POSTCARD_VIEW_WIDTH * 2, 160);
	if (nullptr != funny)
	{
		// A funny one: its scene, doubled in size like the zone pictures
		if (mHasPostcardPicture)
			drawer.drawRect(pictureRect, mPostcardPicture, Color(1.0f, 1.0f, 1.0f, alpha));
		else
			drawer.drawRect(pictureRect, Color(0.2f, 0.25f, 0.35f, alpha));
	}
	else if (mHasPostcardPicture)
		drawer.drawRect(pictureRect, mPostcardPicture, Color(1.0f, 1.0f, 1.0f, alpha));
	else
		drawer.drawRect(pictureRect, Color(0.2f, 0.25f, 0.35f, alpha));

	// A stamp in the corner: the stamp card's monitor of the day it arrived, with a postmark ring over it
	if (mHasJournalIcons)
	{
		const Recti stampRect(card.x + card.width - 46, card.y + 3, 40, 40);
		drawer.drawRect(Recti(stampRect.x - 2, stampRect.y - 2, stampRect.width + 4, stampRect.height + 4), Color(0.98f, 0.95f, 0.86f, alpha));
		drawer.drawRect(Recti(stampRect.x + 4, stampRect.y + 4, 32, 32), mStampIcons[(postcard.mDate % 7)], Color(1.0f, 1.0f, 1.0f, alpha));
	}

	// "Greetings from Hydrocity" and the view's caption, on a dark band (the game's fonts have dark outlines, made for light text)
	const int bandY = pictureRect.y + pictureRect.height + 2;
	drawer.drawRect(Recti(pictureRect.x, bandY, pictureRect.width, 30), Color(0.22f, 0.1f, 0.05f, alpha));
	std::string line;
	if (nullptr != funny)
	{
		drawer.printText(global::mSonicFontB, Recti(card.x + 14, bandY + 3, 0, 10), funny->mHeadline, 1, Color(1.0f, 0.85f, 0.2f, alpha));
		drawer.printText(global::mOxyfontTiny, Recti(card.x + card.width - 14, bandY + 4, 0, 10), "Arrived " + n3ds::journal::formatDate(postcard.mDate), 3, Color(0.9f, 0.8f, 0.7f, alpha));
		if (funny->mScribbled)
			printScribbled(drawer, global::mOxyfontTiny, card.x + 14, bandY + 18, funny->mMessage, Color(1.0f, 1.0f, 1.0f, alpha));
		else
			drawer.printText(global::mOxyfontTiny, Recti(card.x + 14, bandY + 18, 0, 10), funny->mMessage, 1, Color(1.0f, 1.0f, 1.0f, alpha));
	}
	else
	{
		String greeting(getPostcardZoneName(spriteName));
		greeting.upperCase();
		const String headline = (nullptr != view && nullptr != view->mHeadline) ? String(view->mHeadline) : String(0, "GREETINGS FROM %s", greeting.toStdString().c_str());
		drawer.printText(global::mSonicFontB, Recti(card.x + 14, bandY + 3, 0, 10), headline, 1, Color(1.0f, 0.85f, 0.2f, alpha));
		const int acts = (postcard.mZone == 11 || postcard.mZone == 12 || postcard.mZone == 14) ? 1 : 2;
		line = (nullptr != view) ? view->mCaption : std::string();
		if (acts > 1)
			line += (line.empty() ? "Act " : "  -  Act ") + std::to_string(postcard.mAct);
	}
	if (nullptr == funny)
	{
		drawer.printText(global::mOxyfontSmall, Recti(card.x + 14, bandY + 17, 0, 10), line, 1, Color(1.0f, 1.0f, 1.0f, alpha));
		drawer.printText(global::mOxyfontTiny, Recti(card.x + card.width - 14, bandY + 18, 0, 10), "Arrived " + n3ds::journal::formatDate(postcard.mDate), 3, Color(0.9f, 0.8f, 0.7f, alpha));
	}

	// How to flip and go back
	const bool canGoLeft = (entry.mSelectedIndex > 0);
	const bool canGoRight = (entry.mSelectedIndex + 1 < entry.mOptions.size());
	const String hint(0, "%s  %d of %d  %s        B: Back", canGoLeft ? "<" : " ", (int)entry.mSelectedIndex + 1, (int)entry.mOptions.size(), canGoRight ? ">" : " ");
	drawer.drawRect(Recti(0, (int)mRect.height - 16, (int)mRect.width, 16), Color(0.0f, 0.0f, 0.0f, 0.9f * alpha));
	drawer.printText(global::mOxyfontSmall, Recti(200, (int)mRect.height - 12, 0, 10), hint, 5, Color(1.0f, 1.0f, 1.0f, alpha));
}

void N3DSMenu::createRobotnik()
{
	if (mRobotnikCreated)
		return;
	mRobotnikCreated = true;

	// All four have the same size: his head is always within the Egg Mobile's width and at the same height
	const uint64 startTicks = svcGetSystemTick();
	mHasRobotnik = true;
	for (int k = 0; k < NUM_ROBOTNIK_SPRITES && mHasRobotnik; ++k)
	{
		mHasRobotnik = n3ds::romsprites::draw(ROM_SPRITES[ROBOTNIK_ROM_SPRITE + k], true, mRobotnik[k].accessBitmap());		// Facing right, to his speech bubble
		mRobotnik[k].bitmapUpdated();
	}
	mHasRobotnikMad = mHasRobotnik;
	for (int k = 0; k < 3 && mHasRobotnikMad; ++k)
	{
		mHasRobotnikMad = n3ds::romsprites::draw(ROM_SPRITES[ROBOTNIK_MAD_ROM_SPRITES[k]], true, mRobotnikMad[k].accessBitmap(), &mRobotnikMadOrigin[k]);
		mRobotnikMad[k].bitmapUpdated();
	}
	// The shadow's icon: Sonic running, gray like the shadow in the game (the brightness only, lifted a bit; see N3DSShadow)
	mHasShadowIcon = true;
	for (int k = 0; k < 4 && mHasShadowIcon; ++k)
	{
		Bitmap& bitmap = mShadowIcon[k].accessBitmap();
		mHasShadowIcon = n3ds::romsprites::draw(ROM_SPRITES[SHADOW_ROM_SPRITE + k], false, bitmap, &mShadowIconOrigin[k]);
		uint32* data = bitmap.getData();
		for (int i = 0; i < bitmap.getPixelCount(); ++i)
		{
			const uint32 color = data[i];
			const uint32 luma = ((color & 0xff) * 77 + ((color >> 8) & 0xff) * 150 + ((color >> 16) & 0xff) * 29) >> 8;
			const uint32 value = 48 + luma * 176 / 255;
			data[i] = (color & 0xff000000) | (value << 16) | (value << 8) | value;
		}
		mShadowIcon[k].bitmapUpdated();
	}
	mHasDust = true;
	for (int k = 0; k < 4 && mHasDust; ++k)
	{
		mHasDust = n3ds::romsprites::draw(ROM_SPRITES[DUST_ROM_SPRITE + k], false, mDust[k].accessBitmap()) &&
				   n3ds::romsprites::draw(ROM_SPRITES[DUST_ROM_SPRITE + k], true, mDust[k + 4].accessBitmap());
		mDust[k].bitmapUpdated();
		mDust[k + 4].bitmapUpdated();
	}
	RMX_LOG_INFO("3DS menu: Robotnik " << (mHasRobotnik ? "drawn" : "could not be drawn") << " from the ROM (" << (int)((svcGetSystemTick() - startTicks) * 1000 / SYSCLOCK_ARM11) << " ms)");
}

void N3DSMenu::renderStats(float alpha)
{
	Drawer& drawer = EngineMain::instance().getDrawer();
	const n3ds::journal::Data& journal = n3ds::journal::get();

	// Darken everything, then a box with the numbers in two columns
	drawer.drawRect(Recti(0, 0, (int)mRect.width, (int)mRect.height), Color(0.0f, 0.0f, 0.0f, 0.6f * alpha));
	const Recti box(8, 6, 384, 228);
	drawer.drawRect(Recti(box.x - 2, box.y - 2, box.width + 4, box.height + 4), Color(0.6f, 0.8f, 1.0f, alpha));
	drawer.drawRect(box, Color(0.02f, 0.1f, 0.35f, alpha));
	drawer.printText(global::mSonicFontB, Recti(200, box.y + 8, 0, 10), "STATS", 5, Color(1.0f, 1.0f, 1.0f, alpha));

	struct Stat
	{
		const char* mName;
		std::string mValue;
		std::string mNote;
		const DrawerTexture* mIcon;
	};
	Stat stats[8];
	{
		const uint64 minutes = journal.mPlaySeconds / 60;
		stats[0] = { "PLAY TIME", (minutes >= 60) ? String(0, "%u h %02u min", (unsigned)(minutes / 60), (unsigned)(minutes % 60)).toStdString() : String(0, "%u min", (unsigned)minutes).toStdString(),
					 "Since the journal began", &mJournalIcons[0] };
	}
	stats[1] = { "DAYS PLAYED", formatNumber(journal.mDaysPlayed), "They don't need to be in a row", &mJournalIcons[1] };
	stats[2] = { "SONIC'S STEPS", formatNumber((uint32)std::min<uint64>(journal.mGameSteps, 0xffffffff)), "Running around in the game", &mJournalIcons[2] };
	stats[3] = { "PLAY COINS SPENT", formatNumber(journal.mPlayCoinsSpent), (journal.mThingsBought == 1) ? std::string("On 1 thing in this menu") : ("On " + formatNumber(journal.mThingsBought) + " things in this menu"), &mJournalIcons[3] };
	{
		const std::vector<SharedDatabase::Achievement>& achievements = SharedDatabase::getAchievements();
		int completed = 0;
		for (const SharedDatabase::Achievement& achievement : achievements)
		{
			if (PlayerProgress::instance().mAchievements.getAchievementState(achievement.mType) != 0)
				++completed;
		}
		stats[4] = { "ACHIEVEMENTS", String(0, "%d / %d", completed, (int)achievements.size()).toStdString(), "Completed so far", &mJournalIcons[4] };
	}
	stats[5] = { "SCREENSHOTS", formatNumber(journal.mScreenshots), "Taken with L + R", &mJournalIcons[5] };
	stats[6] = { "POSTCARDS", String(0, "%d / %d", (int)journal.mPostcards.size(), n3ds::journal::getNumPossiblePostcards()).toStdString(),
				 (journal.mCardsCompleted == 1) ? std::string("1 stamp card completed") : (formatNumber(journal.mCardsCompleted) + " stamp cards completed"), &mStampIcons[6] };
	stats[7] = { "JOURNAL STARTED", n3ds::journal::formatDate(journal.mStartedDate), "Here's to many more days!", &mJournalIcons[6] };

	for (int k = 0; k < 8; ++k)
	{
		const int x = box.x + 10 + (k % 2) * 190;
		const int y = box.y + 28 + (k / 2) * 46;
		drawer.drawRect(Recti(x, y + 4, 32, 32), Color(0.05f, 0.08f, 0.2f, alpha));
		if (mHasJournalIcons)
			drawer.drawRect(Recti(x, y + 4, 32, 32), *const_cast<DrawerTexture*>(stats[k].mIcon), Color(1.0f, 1.0f, 1.0f, alpha));
		drawer.printText(global::mOxyfontSmall, Recti(x + 40, y + 2, 0, 10), stats[k].mName, 1, Color(0.6f, 0.9f, 1.0f, alpha));
		drawer.printText(global::mOxyfontRegular, Recti(x + 40, y + 14, 0, 10), stats[k].mValue, 1, Color(1.0f, 0.85f, 0.2f, alpha));
		drawer.printText(global::mOxyfontTiny, Recti(x + 40, y + 28, 0, 10), stats[k].mNote, 1, Color(0.85f, 0.85f, 0.9f, alpha));
	}

	drawer.printText(global::mOxyfontSmall, Recti(box.x + box.width - 10, box.y + 8, 0, 10), "B: Back", 3, Color(1.0f, 1.0f, 1.0f, alpha));
}

