	std::string formatNumber(uint32 value)
	{
		// With thousands separators, like "12,345"
		std::string digits = std::to_string(value);
		for (int pos = (int)digits.length() - 3; pos > 0; pos -= 3)
			digits.insert((size_t)pos, ",");
		return digits;
	}

