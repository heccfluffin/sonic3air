GameMenuBase::BaseState N3DSMenu::getBaseState() const
{
	switch (mState)
	{
		case State::APPEAR:		  return BaseState::FADE_IN;
		case State::SHOW:		  return BaseState::SHOW;
		case State::CONFIRM:	  return BaseState::SHOW;
		case State::FADE_TO_MENU: return BaseState::FADE_OUT;
		default:				  return BaseState::INACTIVE;
	}
}

void N3DSMenu::setBaseState(BaseState baseState)
{
	switch (baseState)
	{
		case BaseState::INACTIVE: mState = State::INACTIVE;  break;
		case BaseState::FADE_IN:  mState = State::APPEAR;  break;
		case BaseState::SHOW:	  mState = State::SHOW;  break;
		case BaseState::FADE_OUT: mState = State::FADE_TO_MENU;  break;
	}
}

void N3DSMenu::onFadeIn()
{
	mState = State::APPEAR;

	const uint64 startTicks = svcGetSystemTick();
	const auto msSince = [](uint64 ticks)  { return (uint32)((svcGetSystemTick() - ticks) * 1000 / SYSCLOCK_ARM11); };
	mPreviewedTheme.clear();

	// A little greeting, like "Good evening, Name!" - and a hint at a new stamp
	const std::string greeting = n3ds::profile::getGreeting();
	showMessage(n3ds::journal::takeNewStampNotice() ? (greeting + " New stamp in your Journal!") : greeting, false);
	mMessageTimeout = 5.0f;

	// The 3DS step counter, for the journal (quick, no SD card involved)
	mHasSteps = n3ds::journal::getSteps(mStepsTotal);

	// Play Coins and the player's own pictures get read in the background: the menu opens right away, they show up when ready
	const uint32 greetingMs = msSince(startTicks);
	startBackgroundLoading();
	rebuildTabs();
	const uint64 iconTicks = svcGetSystemTick();
	createIcons();
	const uint32 iconMs = msSince(iconTicks);
	const uint64 backgroundTicks = svcGetSystemTick();

	mMenuBackground->showPreview(false, false);
	mMenuBackground->startTransition(MenuBackground::Target::BLUE);

	for (size_t k = 0; k < NUM_TABS; ++k)
	{
		for (size_t i = 0; i < mTabs[k].mMenuEntries.size(); ++i)
		{
			mTabs[k].mMenuEntries[i].mAnimation.mHighlight = 0.0f;
		}
	}

	const uint32 backgroundMs = msSince(backgroundTicks);
	const uint64 musicTicks = svcGetSystemTick();
	AudioOut::instance().setMenuMusic(0x2f);
	const uint32 musicMs = msSince(musicTicks);

	const uint32 ms = msSince(startTicks);
	if (ms >= 30)
		RMX_LOG_INFO("3DS menu: opening took " << ms << " ms on the main thread (greeting " << greetingMs << ", icons " << iconMs << ", background " << backgroundMs << ", music " << musicMs << ")");
}

